export function opsTaskLabel(lang:Language,item:Record<string,any>):string {
 const regional=['bs','hr','sr'].includes(lang);
 const key=String(item.key||'');
 if(/^(leg|service)_[0-9a-f]{8}-/i.test(key)||/^(Leg|Service) [0-9a-f]{8}-/i.test(String(item.label||''))){
  if(item.label&&!/^(Leg|Service) [0-9a-f]{8}-/i.test(String(item.label)))return String(item.label).split(' · ').map(value=>regional?value:english[value]||value).join(' · ');
  const service=key.replace(/^service_[0-9a-f-]{36}_/i,'');
  const labels:Record<string,string>={shipping_line:'Shipping line coordination',bl:'Bill of lading / release',carrier:'Carrier and vehicle',cmr:'CMR / consignment note',flight:'Flight booking',awb:'Air waybill',operator:'Rail operator and terminal',rail_note:'Rail consignment note',receipt:'Goods receipt',dispatch:'Goods dispatch',declaration:'Customs declaration',release:'Customs release'};
  return labels[service]||(regional?'Transportna dionica':'Transport leg');
 }
 const builtIn=checklistLabel(lang,item.key);
 if(!item.label||item.label===String(item.key).replaceAll('_',' ')||item.label===item.key)return builtIn;
 return String(item.label).split(' · ').map(value=>regional?value:english[value]||value).join(' · ');
}
export function useOpsCopy() {
 const lang=useContext(OpsLanguage);
 const t=(value:string):string => ['bs','hr','sr'].includes(lang) ? value : english[value] || value;
 const taskLabel=(item:Record<string,any>):string => opsTaskLabel(lang,item);
 return {t,taskLabel,lang};
}
